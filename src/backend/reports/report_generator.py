"""
Evidence-Verified Clinical Decision Support Report Generator.

This module provides the capstone report generation and export capabilities
for the evidence-verified CDSS pipeline:

  1. EnhancedReportGenerator:
     - Assembles the comprehensive EnhancedCDSReport from EnhancedAgentState.
     - Merges synthesis outputs with claim-level verification results.
     - Integrates evidence bundles and GRADE quality ratings.
     - Generates automated safety warnings from refuted claims, critical missing
       patient data, and severe drug interactions.
     - Implements clinical review triage (APPROVED / REQUIRES_CORRECTION / PENDING).
     - Incorporates uncertainty quantification and mandatory medical disclaimers.

  2. ReportMarkdownExporter:
     - Formats EnhancedCDSReport into clinician-ready, structured Markdown.
     - Includes rich diagnostic tables, citation provenance, claim-by-claim
       verification tables, uncertainty assessments, and safety alerts.

  3. ReportJSONExporter:
     - Exports EnhancedCDSReport as fully validated, structured JSON
       using Pydantic v2 serialization.
"""
